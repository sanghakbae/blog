if (!ts || Math.abs(Date.now() / 1000 - ts) > 300) return reject('시각 오차')

// 2) 논스 재사용 확인
const nonce = req.header('X-Nonce')
if (!nonce || (await seen(nonce))) return reject('재사용된 논스')

// 3) 키 조회 — 식별자로 어떤 키인지 정한다
const key = await keys.get(req.header('X-Key-Id'))
