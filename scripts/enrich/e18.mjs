// 4) 서명 계산과 비교 — 반드시 시간 일정 비교
const payload = [req.method, req.path, ts, nonce, sha256(rawBody)].join('\n')
const expected = hmacSha256(key.secret, payload)
if (!timingSafeEqual(Buffer.from(expected), Buffer.from(req.header('X-Signature') ?? ''))) {
  return reject('서명 불일치')
}

await markNonce(nonce, 600)     // 허용 오차보다 길게 보관
